"""Transport document PDFs: AWB, DG declaration, packing list.

Generated with reportlab into data/documents/. Layout is deliberately simple
but field-complete — enough to demonstrate e-document flows in interviews.
"""

from pathlib import Path

from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas as pdfcanvas

from app.config import ROOT_DIR, get_settings

DOCS_DIR = ROOT_DIR / "data" / "documents"


def _draw_base(c: pdfcanvas.Canvas, title: str, shipment: dict, awb: dict | None):
    width, height = A4
    c.setFont("Helvetica-Bold", 16)
    c.drawString(25 * mm, height - 25 * mm, title)
    c.setFont("Helvetica", 9)
    c.drawString(25 * mm, height - 32 * mm, "HKG Cargo Control Tower — synthetic transport document (demo)")
    y = height - 45 * mm

    def line(label, value):
        nonlocal y
        c.setFont("Helvetica-Bold", 9)
        c.drawString(25 * mm, y, label)
        c.setFont("Helvetica", 9)
        c.drawString(70 * mm, y, str(value))
        y -= 7 * mm

    line("AWB No.", (awb or {}).get("awb_no", "—"))
    line("Shipment", shipment["shipment_id"])
    line("Shipper / Customer", shipment["customer_name"])
    line("Routing", f"{shipment['origin_location']} → {shipment['destination_location']} ({shipment['transport_chain_type']})")
    line("Commodity", shipment["cargo_category"])
    line("Chargeable Weight", f"{shipment['total_chargeable_weight_kg']:,.1f} kg")
    line("Contracted Revenue", f"USD {shipment['contracted_revenue_usd']:,.2f}")
    line("Booking Date", str(shipment["booking_ts"])[:16])
    return y


def generate_awb(shipment: dict, awb: dict) -> Path:
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    path = DOCS_DIR / f"AWB_{shipment['shipment_id']}.pdf"
    c = pdfcanvas.Canvas(str(path), pagesize=A4)
    y = _draw_base(c, "AIR WAYBILL", shipment, awb)

    y -= 6 * mm
    c.setFont("Helvetica-Bold", 10)
    c.drawString(25 * mm, y, "Handling Information")
    y -= 7 * mm
    c.setFont("Helvetica", 9)
    for line in [
        "Freight prepaid. Chargeable weight per IATA TACT rules.",
        "Cargo accepted in apparent good order and condition for carriage.",
        "e-AWB: paperless contract — FWB/FHL transmitted via Cargo-XML.",
    ]:
        c.drawString(30 * mm, y, f"- {line}")
        y -= 6 * mm
    c.setFont("Helvetica-Oblique", 8)
    c.drawString(25 * mm, 15 * mm, "Synthetic document generated by HKG Cargo Control Tower — not a legal transport document.")
    c.showPage()
    c.save()
    return path


def generate_dg_decl(shipment: dict) -> Path:
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    path = DOCS_DIR / f"DG_DECL_{shipment['shipment_id']}.pdf"
    c = pdfcanvas.Canvas(str(path), pagesize=A4)
    y = _draw_base(c, "SHIPPER'S DECLARATION FOR DANGEROUS GOODS", shipment, None)

    y -= 6 * mm
    c.setFont("Helvetica-Bold", 10)
    c.drawString(25 * mm, y, "Dangerous Goods Specification")
    y -= 7 * mm
    c.setFont("Helvetica", 9)
    rows = [
        ("UN Number", "UN3480"),
        ("Proper Shipping Name", "Lithium ion batteries"),
        ("Class / Div", "9"),
        ("Packing Group", "— (Class 9 has none for UN3480)"),
        ("Quantity & Type of Packing", f"{shipment['total_chargeable_weight_kg']:,.1f} kg net, in UN-spec inner packings"),
        ("Emergency Contact", "+852-0000-0000 (24h, synthetic)"),
        ("Declaration", "I hereby declare that the contents of this consignment are fully and accurately described above by the proper shipping name, and are classified, packaged, marked and labelled/placarded, and are in all respects in proper condition for transport according to applicable international and national governmental regulations."),
    ]
    for label, value in rows:
        c.setFont("Helvetica-Bold", 9)
        c.drawString(25 * mm, y, label)
        c.setFont("Helvetica", 9)
        for i, chunk in enumerate([value[i:i + 95] for i in range(0, len(value), 95)]):
            c.drawString(70 * mm, y if i == 0 else y - 5 * mm, chunk)
            if i:
                y -= 5 * mm
        y -= 9 * mm
    c.setFont("Helvetica-Oblique", 8)
    c.drawString(25 * mm, 15 * mm, "Synthetic demonstration document — IATA DGR format simplified.")
    c.showPage()
    c.save()
    return path


def generate_packing_list(shipment: dict, legs: list[dict]) -> Path:
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    path = DOCS_DIR / f"PACKING_LIST_{shipment['shipment_id']}.pdf"
    c = pdfcanvas.Canvas(str(path), pagesize=A4)
    y = _draw_base(c, "PACKING LIST", shipment, None)

    y -= 8 * mm
    c.setFont("Helvetica-Bold", 9)
    c.drawString(25 * mm, y, "Leg")
    c.drawString(60 * mm, y, "Mode")
    c.drawString(90 * mm, y, "Routing")
    c.drawString(140 * mm, y, "Distance (km)")
    y -= 6 * mm
    c.setFont("Helvetica", 9)
    for leg in legs:
        c.drawString(25 * mm, y, str(leg["leg_sequence"]))
        c.drawString(60 * mm, y, leg["transport_mode"])
        c.drawString(90 * mm, y, f"{leg['origin_facility']} → {leg['destination_facility']}")
        c.drawString(140 * mm, y, f"{leg['distance_km']:,.0f}")
        y -= 6 * mm
    c.setFont("Helvetica-Oblique", 8)
    c.drawString(25 * mm, 15 * mm, "Synthetic document generated by HKG Cargo Control Tower.")
    c.showPage()
    c.save()
    return path
